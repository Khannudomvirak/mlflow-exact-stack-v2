#!/bin/sh
# Creates one MinIO identity per consumer and scopes it to that service's bucket.
#
# Runs once per `docker compose up` in the same pinned MinIO image (it ships
# `mc`), after `minio-init` created the buckets and after `vault-init` generated
# each service's access key. The generated keys are the same ones the consumer
# later reads from Vault through its own AppRole, so the storage layer enforces
# the split: Nessie can only touch `warehouse`, MLflow only `mlflow`.
set -eu

: "${MINIO_ROOT_USER:?MINIO_ROOT_USER must be set}"
: "${MINIO_ROOT_PASSWORD:?MINIO_ROOT_PASSWORD must be set}"

ENDPOINT="${MINIO_ENDPOINT:-http://minio:9000}"
SEED_DIR="${SEED_DIR:-/s3seed}"
CONFIG_DIR="${MC_CONFIG_DIR:-/tmp/.mc}"

export MC_CONFIG_DIR="$CONFIG_DIR"
mkdir -p "$CONFIG_DIR"

mc alias set local "$ENDPOINT" "$MINIO_ROOT_USER" "$MINIO_ROOT_PASSWORD" >/dev/null

echo "minio-provision: waiting for $ENDPOINT"
i=0
until mc ready local >/dev/null 2>&1; do
  i=$((i + 1))
  if [ "$i" -gt 60 ]; then
    echo "minio-provision: MinIO did not become ready" >&2
    exit 1
  fi
  sleep 2
done

provision() {
  svc="$1"
  bucket="$2"
  policy="lakehouse-$bucket-rw"

  # ACCESS_KEY / SECRET_KEY were generated by vault-init and stored in Vault.
  . "$SEED_DIR/$svc.env"

  cat > "/tmp/$policy.json" <<JSON
{
  "Version": "2012-10-17",
  "Statement": [
    {
      "Effect": "Allow",
      "Action": ["s3:GetBucketLocation", "s3:ListBucket", "s3:ListBucketMultipartUploads"],
      "Resource": ["arn:aws:s3:::$bucket"]
    },
    {
      "Effect": "Allow",
      "Action": [
        "s3:GetObject",
        "s3:PutObject",
        "s3:DeleteObject",
        "s3:AbortMultipartUpload",
        "s3:ListMultipartUploadParts"
      ],
      "Resource": ["arn:aws:s3:::$bucket/*"]
    }
  ]
}
JSON

  # Canned policies are created once and stay stable. `user add` also updates
  # the secret when the user already exists, so a re-run rotates the key in
  # place: one MinIO identity per service, never an extra one.
  mc admin policy create local "$policy" "/tmp/$policy.json" >/dev/null 2>&1 || true
  mc admin user add local "$ACCESS_KEY" "$SECRET_KEY" >/dev/null
  mc admin policy attach local "$policy" --user "$ACCESS_KEY" >/dev/null

  echo "minio-provision: $svc -> user $ACCESS_KEY, rw only on s3://$bucket (policy $policy)"
}

provision nessie warehouse
provision mlflow mlflow

echo "minio-provision: done"
